// In Hindi and Marathi the official English name is kept as the subtitle (shown where hindiName was),
// so people can still match the scheme to forms and portals.
export function localizeSchemes(schemes: SchemeItem[], lang: Language): SchemeItem[] {
  if (lang === 'English') return schemes;
  return schemes.map((s) => {
    const text = SCHEME_TEXT[lang][s.id];
    return text ? { ...s, ...text, hindiName: s.name } : s;
  });
}

